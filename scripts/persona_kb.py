def _math(rng: random.Random) -> tuple[str, str]:
    a, b = rng.randint(2, 999), rng.randint(2, 99)
    k = rng.choice(["add", "sub", "mul"])
    if k == "add":
        return f"{a} 加 {b} 等于多少？", f"{a + b}。"
    if k == "sub":
        a, b = max(a, b), min(a, b)
        return f"{a} 减 {b} 等于多少？", f"{a - b}。"
    return f"{a} 乘以 {b} 等于多少？", f"{a * b}。"


def _unit(rng: random.Random) -> tuple[str, str]:
    s, d, k = rng.choice(UNITS)
    n = rng.randint(2, 999)
    v = n * k
    vs = str(int(v)) if float(v).is_integer() else str(v)
    return f"{n} {s}等于多少{d}？", f"{vs} {d}。"


